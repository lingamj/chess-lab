def eval_pst(board):
    score = 0
    for r in range(8):
        for c in range(8):
            p = board.board[r][c]
            if p == ".":
                continue
            sq = r * 8 + c
            if p == "P":
                pst = pst_pawn[sq]
            elif p == "N":
                pst = pst_knight[sq]
            elif p == "B":
                pst = pst_bishop[sq]
            elif p == "R":
                pst = pst_rook[sq]
            elif p == "Q":
                pst = pst_queen[sq]
            elif p == "K":
                pst = pst_king[sq]
            elif p == "p":
                pst = -pst_pawn[63 - sq]
            elif p == "n":
                pst = -pst_knight[63 - sq]
            elif p == "b":
                pst = -pst_bishop[63 - sq]
            elif p == "r":
                pst = -pst_rook[63 - sq]
            elif p == "q":
                pst = -pst_queen[63 - sq]
            elif p == "k":
                pst = -pst_king[63 - sq]
            else:
                pst = 0
            score += pst
    return score
